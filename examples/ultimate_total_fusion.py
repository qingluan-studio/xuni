def main():
    print("=" * 78)
    print("终极融合：所有实验产物 → 一个物质（属性全融合）")
    print("=" * 78)

    engine = SubstanceFusionEngine()

    # 注册全部物质
    print(f"\n  注册 {len(ALL_SUBSTANCES)} 种物质...")
    for name, props in ALL_SUBSTANCES:
        engine.register_substance(name, props)

    # 链式融合
    print(f"\n  开始链式融合...")
    print(f"  {'步骤':>4}  {'当前物质':<16}  {'下一个':<20}  {'融合类型':<10}  {'属性键数':<8}")
    print(f"  {'─'*4}  {'─'*16}  {'─'*20}  {'─'*10}  {'─'*8}")

    current = ALL_SUBSTANCES[0][0]
    accum = dict(ALL_SUBSTANCES[0][1])
    type_counts = {}  # 统计融合类型

    for i in range(1, len(ALL_SUBSTANCES)):
        nxt_name, nxt_props = ALL_SUBSTANCES[i]
        product = engine.fuse(current, nxt_name)
        ftype = product.fusion_type.name
        type_counts[ftype] = type_counts.get(ftype, 0) + 1

        # 属性叠加
        new_props = {}
        for k in set(list(accum.keys()) + list(nxt_props.keys())):
            va = accum.get(k, 0.0)
            vb = nxt_props.get(k, 0.0)
            new_props[k] = va + vb
        accum = new_props
        current = ftype

        if i % 50 == 0 or i == len(ALL_SUBSTANCES) - 1:
            print(f"  {i:4d}  {'...':<16}  {nxt_name:<20}  {ftype:<10}  {len(accum):<8}")

    # 最终结果
    total_attrs = len(accum)
    sum_values = sum(v for v in accum.values() if isinstance(v, (int, float)))

    print(f"\n{'='*78}")
    print(f"  融合完成！")
    print(f"  总物质数: {len(ALL_SUBSTANCES)}")
    print(f"  总属性键: {total_attrs}")
    print(f"  属性值总和: {sum_values:.4f}")
    print(f"  融合类型统计: {type_counts}")

    # 命名
    final_name = "☯⚛🧠∇∞ΨΩ◈✨ 【现实×虚拟·万物归一·终极存在】"
    print(f"\n{'='*78}")
    print(f"  最终产物: {final_name}")
    print(f"{'='*78}")

    # 按数值排序展示全部属性
    print(f"\n  全部 {total_attrs} 个属性（按数值降序）:")
    sorted_attrs = sorted(
        accum.items(),
        key=lambda x: -abs(x[1]) if isinstance(x[1], (int, float)) else 0
    )
    for k, v in sorted_attrs:
        if isinstance(v, (int, float)):
            print(f"    {k:<22}: {v:>25.4f}")

    # 关键指标
    print(f"\n{'='*78}")
    print(f"  关键指标:")

    Z = accum.get("Z", 0)
    mass = accum.get("原子量", 0)
    EN = accum.get("电负性", 0)
    avg_EN = EN / 118 if EN > 0 else 0
