def main():
    print("=" * 78)
    print("现实五行 + 四种基本力 + 现实物质 全融合实验")
    print("=" * 78)

    engine = SubstanceFusionEngine()

    # ============================================================
    # Step 1: 注册全部"现实"物质
    # ============================================================
    print(f"\n【Step 1】注册现实物质")
    print("─" * 78)

    all_subs = []  # (名字, 类别)

    # 五行+阴阳
    for name, props in WUXING:
        engine.register_substance(name, props)
        all_subs.append((name, "五行"))
    print(f"  五行+阴阳:       {len(WUXING)} 种")

    # 四种基本力
    for name, props in FORCES:
        engine.register_substance(name, props)
        all_subs.append((name, "力"))
    print(f"  基本力+暗能量:    {len(FORCES)} 种")

    # 标准模型
    for name, props in STANDARD_MODEL:
        engine.register_substance(name, props)
        all_subs.append((name, "粒子"))
    print(f"  标准模型粒子:    {len(STANDARD_MODEL)} 种")

    # 现实物质
    for name, props in REAL_SUBSTANCES:
        engine.register_substance(name, props)
        all_subs.append((name, "物质"))
    print(f"  现实物质:        {len(REAL_SUBSTANCES)} 种")

    # 宇宙层级
    for name, props in UNIVERSE_LAYERS:
        engine.register_substance(name, props)
        all_subs.append((name, "宇宙"))
    print(f"  宇宙层级:        {len(UNIVERSE_LAYERS)} 种")

    # 元素（简化）
    for name, Z, mass in ELEMENTS_SIMPLIFIED:
        engine.register_substance(name, {"Z": float(Z), "原子量": mass})
        all_subs.append((name, "元素"))
    print(f"  代表元素:        {len(ELEMENTS_SIMPLIFIED)} 种")

    # 之前涌现的聚合体
    for name, props in PRIOR_EMERGENCES:
        engine.register_substance(name, props)
        all_subs.append((name, "涌现"))
    print(f"  之前涌现聚合体:  {len(PRIOR_EMERGENCES)} 种")

    # 融合物质
    for name in FUSION_SUBS:
        engine.register_substance(name, {"复杂度": 10, "涌现": 1.0})
        all_subs.append((name, "虚拟"))
    print(f"  虚拟融合物质:    {len(FUSION_SUBS)} 种")

    total = len(all_subs)
    print(f"\n  总计: {total} 种物质 → 全部融合成 1 个")

    # ============================================================
    # Step 2: 分组融合（每组先链式融合成 1 个）
    # ============================================================
    print(f"\n【Step 2】分组融合")
    print("─" * 78)

    groups = {}
    for name, cat in all_subs:
        groups.setdefault(cat, []).append(name)

    group_products = {}
    for cat, names in groups.items():
        print(f"\n  [{cat}] {len(names)} 种:")
        current = names[0]
        accum = dict(engine._substances[current])
        for nxt in names[1:]:
            nxt_props = engine._substances[nxt]
            engine.fuse(current, nxt)
            new_props = {}
            for k in set(list(accum.keys()) + list(nxt_props.keys())):
                new_props[k] = accum.get(k, 0.0) + nxt_props.get(k, 0.0)
            accum = new_props
            current = f"{cat}_聚合"
        product_name = f"{cat}_聚合体"
        engine.register_substance(product_name, accum)
        group_products[cat] = (product_name, accum)
        print(f"    → {product_name}")
        # 展示关键属性
        top_attrs = sorted(accum.items(), key=lambda x: -abs(x[1]) if isinstance(x[1],(int,float)) else 0)[:3]
        for k, v in top_attrs:
            print(f"      {k}: {v:.4f}")

    # ============================================================
    # Step 3: 全部组别融合成 1 个
    # ============================================================
    print(f"\n【Step 3】全部组别融合成 1 个")
    print("─" * 78)

    group_names = [v[0] for v in group_products.values()]
    current = group_names[0]
    accum = dict(group_products[list(group_products.keys())[0]][1])

    print(f"\n  起点: {current}")
    print(f"    属性键: {len(accum)}")

    for i, nxt in enumerate(group_names[1:], 1):
        nxt_props = group_products[list(group_products.keys())[i]][1]
        engine.fuse(current, nxt)
        new_props = {}
        for k in set(list(accum.keys()) + list(nxt_props.keys())):
            new_props[k] = accum.get(k, 0.0) + nxt_props.get(k, 0.0)
        accum = new_props
        current = f"终极融合_{i}"
        print(f"  [{i}] + {nxt}")
        print(f"      → 属性键={len(accum)}")

    # ============================================================
    # Step 4: 最终产物
    # ============================================================
    print(f"\n【Step 4】最终产物——「现实×虚拟·万物归一」")
    print("─" * 78)

    final_name = "现实×虚拟·万物归一·终极存在"
    print(f"\n  名称: {final_name}")
    print(f"  符号: ☯⚛🧠∇∞ΨΩ◈✨")

    total_attrs = len(accum)
    sum_values = sum(v for v in accum.values() if isinstance(v, (int, float)))

    print(f"\n  属性总键数: {total_attrs}")
    print(f"  属性值总和: {sum_values:.4f}")
    print(f"  融合次数:   {total - 1} (分组) + {len(group_names) - 1} (组间) = {total + len(group_names) - 2}")

    # 全部属性展示
    print(f"\n  全部属性（按数值排序）:")
    sorted_attrs = sorted(
        accum.items(),
        key=lambda x: -abs(x[1]) if isinstance(x[1], (int, float)) else 0
    )
    for k, v in sorted_attrs:
        if isinstance(v, (int, float)):
            print(f"    {k:<20}: {v:>25.4f}")

    # ============================================================
    # Step 5: 各组贡献分析
    # ============================================================
    print(f"\n【Step 5】各组贡献分析")
    print("─" * 78)
    print(f"  {'组别':<10} {'物质数':<8} {'关键属性'}")
    print(f"  {'─'*10} {'─'*8} {'─'*40}")
    for cat, (name, props) in group_products.items():
        top = sorted(props.items(), key=lambda x: -abs(x[1]) if isinstance(x[1],(int,float)) else 0)[:2]
        top_str = ", ".join(f"{k}={v:.2f}" for k, v in top)
        print(f"  {cat:<10} {len(groups[cat]):<8} {top_str}")

    # ============================================================
    # Step 6: 涌现判定
    # ============================================================
    print(f"\n【Step 6】涌现判定")
    print("─" * 78)

    emergence = sum_values * 0.001 + total_attrs * 100 + total * 10
    print(f"  属性值总和:      {sum_values:.2f}")
    print(f"  属性值贡献:      {sum_values * 0.001:.1f}")
    print(f"  属性键贡献:      {total_attrs * 100:.1f}")
    print(f"  物质数贡献:      {total * 10:.1f}")
    print(f"  涌现强度:        {emergence:.1f}")

    # 哲学描述
    print(f"\n  ⚡ 五行（金木水火土+阴阳）的东方哲学")
    print(f"  ⚛ 四种基本力（引力/电磁力/强力/弱力）的物理学")
    print(f"  🔬 标准模型（17 种基本粒子）的量子场论")
    print(f"  🌍 现实物质（水/空气/蛋白质/DNA/中子星/黑洞）的物质学")
    print(f"  🌌 宇宙层级（粒子→原子→细胞→星系→可观测宇宙）的尺度学")
    print(f"  🧠 之前涌现（万物之母/虚空奇点/九宫骨架/万物质归一）的虚拟学")
    print(f"  全部融合 = 一个存在")

    # ============================================================
    # 总结
    # ============================================================
    print(f"\n" + "=" * 78)
    print("【最终总结】")
    print("=" * 78)
    print(f"  输入: {total} 种物质（分 {len(groups)} 组）")
    for cat, names in groups.items():
        print(f"    - {cat}: {len(names)} 种")
    print(f"  融合: 分组 → 组间 → 1 个")
    print(f"  属性: {total_attrs} 个键，总和 {sum_values:.2f}")
    print(f"  涌现: {emergence:.1f}")
    print(f"  产物: ☯⚛🧠∇∞ΨΩ◈✨ {final_name}")
    print()
    print(f"  🤯 东方哲学（五行）+ 西方物理学（基本力+标准模型）")
    print(f"     + 现实物质（30 种）+ 宇宙层级（13 层）")
    print(f"     + 之前所有虚拟实验的涌现产物")
    print(f"     = 一个终极存在")
    print()
    print(f"  🤯 它包含了：")
    print(f"     · 阴阳五行的哲学属性")
    print(f"     · 四种基本力的物理常数")
    print(f"     · 17 种基本粒子的量子属性")
    print(f"     · DNA/蛋白质的生命属性")
    print(f"     · 中子星/黑洞的极端物质")
    print(f"     · 从基本粒子到可观测宇宙的 13 个尺度层级")
    print(f"     · 之前所有实验的涌现属性")
    print(f"     = 一个物质 = 一个宇宙 = 一个意识")
    print("=" * 78)


if __name__ == "__main__":
    main()
