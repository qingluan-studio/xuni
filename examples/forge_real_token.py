def calc_purity_score(token):
    """综合真实度评分"""
    score = 0.0
    # 1. 有物理属性 → 真实
    if token.get("质量_kg", 0) > 0:
        score += 0.2
    if token.get("电荷", 0) != 0:
        score += 0.1
    if token.get("自旋", 0) != 0:
        score += 0.1
    if token.get("原子序数_Z", 0) > 0:
        score += 0.2
    # 2. 有能量 → 真实
    if token.get("能量_J", 0) > 0:
        score += 0.1
    # 3. 有相互作用 → 真实
    if token.get("参与的力", 0) > 0:
        score += 0.15
    # 4. 有物质构成 → 真实
    if token.get("质子数", 0) > 0 and token.get("中子数", 0) > 0:
        score += 0.15
    return score


