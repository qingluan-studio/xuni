# ============================================================
# 3. 计算差异
# ============================================================
def calc_diff(real, forged):
    """计算数值差异"""
    results = []
    for key in real.keys():
        if key in forged and isinstance(real[key], (int, float)) and isinstance(forged[key], (int, float)):
            r, f = real[key], forged[key]
            if r != 0:
                diff_pct = abs(f - r) / abs(r) * 100
                results.append((key, r, f, diff_pct))
            else:
                results.append((key, r, f, 0.0))
    return results

results = calc_diff(REAL_HYDROGEN, FORGED_TOKEN)

